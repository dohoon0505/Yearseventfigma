/** 전체 지역행 수 — 검색 결과 카운트 표기용. */
export const INTAKE_TOTAL = INTAKE_GUIDE.reduce((n, [, rows]) => n + rows.length, 0);

/** 시·도 + 지역·장소 부분일치 필터.
 *  매치 0인 시·도 그룹을 통째로 제거한다 — 표가 rowspan 으로 시·도를 병합하므로
 *  렌더되는 행 수와 rows.length 가 항상 일치해야 한다. */
export function filterIntakeGuide(q) {
  const k = String(q || "").trim().toLowerCase();
  if (!k) return INTAKE_GUIDE;
  return INTAKE_GUIDE
    .map(([sido, rows]) => [sido, sido.toLowerCase().includes(k) ? rows : rows.filter((r) => String(r[0]).toLowerCase().includes(k))])
    .filter(([, rows]) => rows.length > 0);
}
