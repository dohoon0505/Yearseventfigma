export function latestInvoiceKey() {
  const keys = Object.keys(INVOICE_DB).filter((k) => (INVOICE_DB[k].rows || []).length);
  return keys.sort().pop() || `${new Date().getFullYear()}-01`;
}

/** 한 해를 12칸으로. **거래가 없는 달도 칸을 만든다** — 달력 감각이 깨지지 않게
 *  비어 있음을 '빈 줄'로 보여 주는 것이 화면 계약이다(빈 해로 가면 12칸 모두 empty). */
export function monthsOf(year) {
  return MONTHS.map((mm) => {
    const ym = `${year}-${mm}`;
    const d = INVOICE_DB[ym];
    const rows = d ? d.rows : [];
    return { ym, mm, rows, issue: d ? d.issue : "", count: rows.length, total: sum(rows), empty: !rows.length };
  });
}

/** 한 달치. 없는 달도 빈 껍데기를 돌려준다(호출부가 null 분기를 하지 않게). */
export function invoiceMonth(ym) {
  const d = INVOICE_DB[ym];
  const rows = d ? d.rows : [];
  return { ym, rows, issue: d ? d.issue : "", count: rows.length, total: sum(rows), empty: !rows.length };
}
