let pass = 0, fail = 0;
const bad = [];
/** check(name, text, asserts) — asserts: { field: 값 | null(비어야 함) }, keep: [원문에 남아야 할 조각] */
function check(name, text, asserts = {}, keep = [], opt = {}) {
  const r = P(text);
  const errs = [];
  if (!r) {
    /* null = 하나도 못 읽음. 다이얼로그가 오류 줄을 띄우고 **원문은 입력칸에 그대로 남는다**
       → 정보 손실이 아니다. '틀린 값' 만 실패로 본다. */
    if (opt.mustFill) errs.push("아무것도 못 읽었다(null) — 채워야 하는 케이스");
    if (errs.length) { fail++; bad.push({ name, errs, got: {} }); } else pass++;
    return;
  }
  const got = r;
  for (const [k, want] of Object.entries(asserts)) {
    const v = got[k] ?? (k === "amount" ? 0 : "");
    if (want === null) { if (v) errs.push(`${k}: 비어야 하는데 "${v}"`); }
    else if (v !== want) errs.push(`${k}: "${want}" 여야 하는데 "${v}"`);
  }
  const note = got.note || "";
  for (const kp of keep) if (!note.includes(kp)) errs.push(`원문 보존 실패: "${kp}" 가 note 에 없음 (note="${note.replace(/\n/g, " / ")}")`);
  if (errs.length) { fail++; bad.push({ name, errs, got }); } else pass++;
}

